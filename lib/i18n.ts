export type MessageKey = keyof typeof zh;

const dictionaries: Record<Locale, { [K in MessageKey]: string }> = { zh, en };

export function t(locale: string, key: MessageKey, vars?: Record<string, string | number>) {
  const table = dictionaries[asLocale(locale)];
  const template = table[key] ?? zh[key];
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (_, name: string) => String(vars[name] ?? ""));
}
